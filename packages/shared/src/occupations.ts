// made on first use, not when the module loads: a module that does work as it loads can't be left out of a bundle, and
// the table would then ship to every page of the web app that uses shared, not only the job title pages
let byCode: Map<string, string> | null = null;

/** The occupation's name for its code, or null for a code the table doesn't have. */
export function occupationName(code: string | null | undefined): string | null {
  if (!code) return null;
  byCode ??= new Map(OCCUPATIONS.map(([c, name]) => [c, name]));
  return byCode.get(code) ?? null;
}

/**
 * Arabic as searched: the alef forms, ى and ي, ة and ه, and the hamza seats each as one letter, without tashkeel or
 * tatweel, digits as 0-9. Alefs are dropped altogether, so a name that lost one (as the table's did) still matches.
 */
export function searchableArabic(text: string): string {
  return text
    .replace(/[\u064B-\u0652\u0670\u0640]/g, '')
    .replace(/[\u0660-\u0669]/g, (d) => String(d.charCodeAt(0) - 0x0660))
    .replace(/[اأإآٱ]/g, '')
    .replace(/ى/g, 'ي')
    .replace(/ة/g, 'ه')
    .replace(/[ؤئ]/g, 'ء')
    .replace(/\s+/g, ' ')
    .trim()
    .toLowerCase();
}

/**
 * The occupations matching what was typed, best first, at most `limit`: by code (its first digits) or by name, every
 * word typed found in it: the name exactly, then names starting with what was typed, then with its first word, then the
 * rest, each in code order.
 */
export function searchOccupations(query: string, limit = 30): (readonly [string, string])[] {
  const q = searchableArabic(query);
  if (!q) return OCCUPATIONS.slice(0, limit);
  if (/^\d+$/.test(q)) return OCCUPATIONS.filter(([code]) => code.startsWith(q)).slice(0, limit);
  const words = q.split(' ');
  const hits: { o: readonly [string, string]; rank: number }[] = [];
  for (const o of OCCUPATIONS) {
    const name = searchableArabic(o[1]);
    if (words.every((w) => name.includes(w))) hits.push({ o, rank: name === q ? 0 : name.startsWith(q) ? 1 : name.startsWith(words[0]) ? 2 : 3 });
  }
  return hits.sort((a, b) => a.rank - b.rank).slice(0, limit).map((h) => h.o);
}
